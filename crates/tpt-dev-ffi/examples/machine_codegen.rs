//! One machine definition, three artefacts.
//!
//! The session machine below is the single source of truth for a C-style
//! session API. The example:
//!
//! 1. checks the machine with `tpt-dev-automata`: it is deterministic and
//!    deadlock-free from its initial state,
//! 2. writes `session_machine.h`, a C header with the state and event enums
//!    and a transition table (`-1` marks an illegal event), and
//! 3. writes `session_guard.rs`, a Rust guard with the same table. The
//!    typestate `Session` in `tpt-dev-ffi` must agree with this guard. The
//!    test `tests/machine_guard.rs` checks that over every event sequence up
//!    to length 5.
//!
//! The "no illegal transition" claim is an exhaustive check over the finite
//! state and event sets, not a solver proof. The machine has no guards, so
//! there are no real-valued conditions for the solver to decide.
//!
//! Usage:
//!
//! ```text
//! cargo run -p tpt-dev-ffi --example machine_codegen -- examples/generated
//! ```

#![allow(clippy::print_stdout, clippy::print_stderr)]

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process;

use tpt_dev_automata::Machine;

/// State names, in table order. The first is the initial state.
const STATES: &[&str] = &["Closed", "Open", "Streaming"];
/// Final states may have no way out.
const FINAL: &[&str] = &["Closed"];
/// Event names, in table order.
const EVENTS: &[&str] = &["open", "start", "stop", "close"];
/// Transitions as (from state, event, to state), by index into the tables above.
const TRANSITIONS: &[(usize, usize, usize)] = &[
    (0, 0, 1), // Closed --open--> Open
    (1, 1, 2), // Open --start--> Streaming
    (2, 2, 1), // Streaming --stop--> Open
    (1, 3, 0), // Open --close--> Closed
];

/// Builds the automata machine and checks it.
fn check_machine() -> Result<Vec<Vec<Option<usize>>>, String> {
    let mut m = Machine::new();
    let states: Vec<_> = STATES.iter().map(|s| m.state(s)).collect();
    for name in FINAL {
        let idx = STATES
            .iter()
            .position(|s| s == name)
            .ok_or_else(|| format!("final state {name} is not declared"))?;
        m.mark_final(states[idx]);
    }
    for &(from, event, to) in TRANSITIONS {
        m.transition(states[from], states[to], EVENTS[event], None)
            .map_err(|e| format!("transition {from} --{}--> {to}: {e:?}", EVENTS[event]))?;
    }

    let mut table = vec![vec![None; EVENTS.len()]; STATES.len()];
    for &(from, event, to) in TRANSITIONS {
        if table[from][event].is_some() {
            return Err(format!(
                "non-deterministic: {} has two transitions on {}",
                STATES[from], EVENTS[event]
            ));
        }
        table[from][event] = Some(to);
    }

    let analysis = m
        .analyze(states[0])
        .map_err(|e| format!("analysis failed: {e:?}"))?;
    if !analysis.is_deadlock_free() {
        return Err(format!(
            "the machine has {} deadlocks",
            analysis.deadlocks.len()
        ));
    }
    if !analysis.unreachable.is_empty() {
        return Err(format!(
            "unreachable states: {}",
            analysis.unreachable.len()
        ));
    }
    println!(
        "machine: {} states, {} events, {} transitions, deterministic, deadlock-free",
        STATES.len(),
        EVENTS.len(),
        TRANSITIONS.len()
    );
    Ok(table)
}

fn c_header(table: &[Vec<Option<usize>>]) -> String {
    let mut out = String::new();
    out.push_str(
        "/* Generated by tpt-dev-ffi's examples/machine_codegen.rs from the session machine.\n \
         * Do not edit by hand: rerun the example to regenerate.\n */\n\
         #ifndef TPT_SESSION_MACHINE_H\n#define TPT_SESSION_MACHINE_H\n\n\
         #include <stdint.h>\n\n",
    );
    out.push_str("typedef enum {\n");
    for (i, s) in STATES.iter().enumerate() {
        let _ = writeln!(out, "    TPT_SESSION_{} = {i},", s.to_uppercase());
    }
    out.push_str("} tpt_session_state;\n");
    let _ = writeln!(out, "#define TPT_SESSION_STATE_COUNT {}\n", STATES.len());
    out.push_str("typedef enum {\n");
    for (i, e) in EVENTS.iter().enumerate() {
        let _ = writeln!(out, "    TPT_SESSION_EV_{} = {i},", e.to_uppercase());
    }
    out.push_str("} tpt_session_event;\n");
    let _ = writeln!(out, "#define TPT_SESSION_EVENT_COUNT {}\n", EVENTS.len());
    out.push_str(
        "/* tpt_session_next[state][event] is the next state, or -1 if the event is illegal there. */\n",
    );
    out.push_str(&format!(
        "static const int8_t tpt_session_next[TPT_SESSION_STATE_COUNT][TPT_SESSION_EVENT_COUNT] = {{\n"
    ));
    for row in table {
        let cells: Vec<String> = row
            .iter()
            .map(|c| match c {
                Some(to) => to.to_string(),
                None => String::from("-1"),
            })
            .collect();
        let _ = writeln!(out, "    {{ {} }},", cells.join(", "));
    }
    out.push_str("};\n\n#endif /* TPT_SESSION_MACHINE_H */\n");
    out
}

fn variant(name: &str) -> String {
    let mut c = name.chars();
    match c.next() {
        Some(first) => first.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

fn rust_guard(table: &[Vec<Option<usize>>]) -> String {
    let mut out = String::new();
    out.push_str(
        "//! Generated by tpt-dev-ffi's examples/machine_codegen.rs from the session machine.\n\
         //! Do not edit by hand: rerun the example to regenerate.\n\n",
    );
    out.push_str(
        "/// The states of the session machine.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum State {\n",
    );
    for (i, s) in STATES.iter().enumerate() {
        let _ = writeln!(out, "    /// State {i}.\n    {} = {i},", variant(s));
    }
    out.push_str("}\n\n/// The events of the session machine.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Event {\n");
    for (i, e) in EVENTS.iter().enumerate() {
        let _ = writeln!(out, "    /// Event {i}.\n    {} = {i},", variant(e));
    }
    out.push_str("}\n\n");
    let _ = writeln!(
        out,
        "/// `NEXT[state][event]` is the next state, or `None` if the event is illegal in that state.\n\
         pub const NEXT: [[Option<State>; {}]; {}] = [",
        EVENTS.len(),
        STATES.len()
    );
    for row in table {
        let cells: Vec<String> = row
            .iter()
            .map(|c| match c {
                Some(to) => format!("Some(State::{})", variant(STATES[*to])),
                None => String::from("None"),
            })
            .collect();
        let _ = writeln!(out, "    [{}],", cells.join(", "));
    }
    out.push_str("];\n\n/// The next state for `event` in `state`, or `None` if the event is illegal there.\n");
    out.push_str(
        "pub const fn next(state: State, event: Event) -> Option<State> {\n    NEXT[state as usize][event as usize]\n}\n",
    );
    out
}

fn main() {
    let dir = env::args()
        .nth(1)
        .unwrap_or_else(|| String::from("examples/generated"));
    let table = match check_machine() {
        Ok(t) => t,
        Err(msg) => {
            eprintln!("machine_codegen: {msg}");
            process::exit(1);
        }
    };
    let dir = Path::new(&dir);
    if let Err(e) = fs::create_dir_all(dir) {
        eprintln!("machine_codegen: cannot create {}: {e}", dir.display());
        process::exit(2);
    }
    for (name, text) in [
        ("session_machine.h", c_header(&table)),
        ("session_guard.rs", rust_guard(&table)),
    ] {
        let path = dir.join(name);
        if let Err(e) = fs::write(&path, text) {
            eprintln!("machine_codegen: cannot write {}: {e}", path.display());
            process::exit(2);
        }
        println!("wrote {}", path.display());
    }
}
