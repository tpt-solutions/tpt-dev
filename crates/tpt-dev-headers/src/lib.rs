//! C header generation from Rust source.
//!
//! Reads a Rust file with `syn` and emits a C header for its public `extern
//! "C"` functions, `#[repr(C)]` structs and enums, opaque types, type aliases
//! and integer constants. Rust documentation becomes Doxygen comments.

#![doc = include_str!("../README.md")]

pub mod build;

use std::fmt::Write as _;

use syn::{
    Attribute, Expr, ExprLit, FnArg, Item, Lit, Meta, Pat, ReturnType, Type, UnOp, Visibility,
};

/// Options for the generated header.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Options {
    /// Name of the include guard macro, such as `MYLIB_H`.
    pub guard: String,
}

/// Why a header could not be generated.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Error {
    /// What was unsupported, and which item it was in.
    pub message: String,
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for Error {}

fn fail<T>(message: impl Into<String>) -> Result<T, Error> {
    Err(Error {
        message: message.into(),
    })
}

/// Generates a C header for the public C-ABI items in `source`.
///
/// ```
/// use tpt_dev_headers::{Options, generate};
///
/// let src = r#"
///     /// Adds two numbers.
///     #[unsafe(no_mangle)]
///     pub extern "C" fn add(a: i32, b: i32) -> i32 { a + b }
/// "#;
/// let h = generate(src, &Options { guard: "DEMO_H".into() }).unwrap();
/// assert!(h.contains("int32_t add(int32_t a, int32_t b);"));
/// assert!(h.contains("/**\n * Adds two numbers."));
/// ```
pub fn generate(source: &str, options: &Options) -> Result<String, Error> {
    let file = syn::parse_file(source).map_err(|e| Error {
        message: format!("cannot parse Rust source: {e}"),
    })?;
    let mut body = String::new();
    for item in &file.items {
        emit_item(item, &mut body)?;
    }
    let mut out = String::new();
    let guard = &options.guard;
    let _ = writeln!(out, "/* Generated by tpt-dev-headers. Do not edit. */");
    let _ = writeln!(out, "#ifndef {guard}");
    let _ = writeln!(out, "#define {guard}");
    out.push('\n');
    out.push_str("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n");
    out.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
    out.push_str(&body);
    out.push_str("#ifdef __cplusplus\n}\n#endif\n\n");
    let _ = writeln!(out, "#endif /* {guard} */");
    Ok(out)
}

fn emit_item(item: &Item, out: &mut String) -> Result<(), Error> {
    match item {
        Item::Fn(f) if is_public(&f.vis) && is_c_abi(f.sig.abi.as_ref()) => {
            let name = f.sig.ident.to_string();
            let mut params = Vec::new();
            for input in &f.sig.inputs {
                match input {
                    FnArg::Typed(pt) => {
                        let pname = match &*pt.pat {
                            Pat::Ident(p) => p.ident.to_string(),
                            _ => {
                                return fail(format!("parameter of `{name}` must be a plain name"));
                            }
                        };
                        params.push(declare(&pt.ty, &pname, &name)?);
                    }
                    FnArg::Receiver(_) => return fail(format!("`{name}` cannot take self")),
                }
            }
            let ret = match &f.sig.output {
                ReturnType::Default => "void".to_string(),
                ReturnType::Type(_, t) => ctype(t, &name)?,
            };
            let plist = if params.is_empty() {
                "void".to_string()
            } else {
                params.join(", ")
            };
            write_doc(&f.attrs, out);
            let sep = if ret.ends_with('*') { "" } else { " " };
            let _ = writeln!(out, "{ret}{sep}{name}({plist});\n");
        }
        Item::Struct(s) if is_public(&s.vis) => {
            let name = s.ident.to_string();
            write_doc(&s.attrs, out);
            if has_repr_c(&s.attrs) {
                let _ = writeln!(out, "typedef struct {name} {{");
                if let syn::Fields::Named(fields) = &s.fields {
                    for f in &fields.named {
                        let fname = f.ident.as_ref().map(|i| i.to_string()).unwrap_or_default();
                        let docs = doc_lines(&f.attrs);
                        if !docs.is_empty() {
                            write_block(out, "    ", &docs);
                        }
                        let decl = declare(&f.ty, &fname, &name)?;
                        let _ = writeln!(out, "    {decl};");
                    }
                } else if !matches!(s.fields, syn::Fields::Unit) {
                    return fail(format!(
                        "`{name}`: only named fields are supported in #[repr(C)] structs"
                    ));
                }
                let _ = writeln!(out, "}} {name};\n");
            } else {
                // Not repr(C): callers only hold a pointer to it.
                let _ = writeln!(out, "typedef struct {name} {name};\n");
            }
        }
        Item::Enum(e) if is_public(&e.vis) => {
            let name = e.ident.to_string();
            write_doc(&e.attrs, out);
            let _ = writeln!(out, "typedef enum {name} {{");
            let mut next: i128 = 0;
            for v in &e.variants {
                if let Some((_, expr)) = &v.discriminant {
                    next = eval_int(expr).ok_or_else(|| Error {
                        message: format!(
                            "`{name}::{}`: discriminant must be an integer literal",
                            v.ident
                        ),
                    })?;
                }
                let _ = writeln!(out, "    {name}_{} = {next},", v.ident);
                next += 1;
            }
            let _ = writeln!(out, "}} {name};\n");
        }
        Item::Type(t) if is_public(&t.vis) => {
            let name = t.ident.to_string();
            write_doc(&t.attrs, out);
            let decl = declare(&t.ty, &name, &name)?;
            let _ = writeln!(out, "typedef {decl};\n");
        }
        Item::Const(c) if is_public(&c.vis) => {
            let name = c.ident.to_string();
            let value = eval_int(&c.expr).ok_or_else(|| Error {
                message: format!("const `{name}`: only integer constants are supported"),
            })?;
            write_doc(&c.attrs, out);
            let _ = writeln!(out, "#define {name} {value}\n");
        }
        _ => {}
    }
    Ok(())
}

fn is_public(v: &Visibility) -> bool {
    matches!(v, Visibility::Public(_))
}

fn is_c_abi(abi: Option<&syn::Abi>) -> bool {
    match abi {
        Some(a) => a.name.as_ref().is_some_and(|n| n.value() == "C"),
        None => false,
    }
}

fn has_repr_c(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path().is_ident("repr")
            && matches!(&a.meta, Meta::List(l) if l.tokens.to_string().contains('C'))
    })
}

/// Writes the item's `///` documentation as a Doxygen block comment.
fn write_doc(attrs: &[Attribute], out: &mut String) {
    let lines = doc_lines(attrs);
    if !lines.is_empty() {
        write_block(out, "", &lines);
    }
}

/// Writes a Doxygen block comment at `indent`.
fn write_block(out: &mut String, indent: &str, lines: &[String]) {
    let _ = writeln!(out, "{indent}/**");
    for l in lines {
        if l.is_empty() {
            let _ = writeln!(out, "{indent} *");
        } else {
            let _ = writeln!(out, "{indent} * {l}");
        }
    }
    let _ = writeln!(out, "{indent} */");
}

/// The documentation lines on a set of attributes.
fn doc_lines(attrs: &[Attribute]) -> Vec<String> {
    let mut lines = Vec::new();
    for a in attrs {
        if let Meta::NameValue(nv) = &a.meta
            && a.path().is_ident("doc")
            && let Expr::Lit(ExprLit {
                lit: Lit::Str(s), ..
            }) = &nv.value
        {
            lines.push(s.value().trim().to_string());
        }
    }
    lines
}

/// Integer value of a literal, optionally negated.
fn eval_int(e: &Expr) -> Option<i128> {
    match e {
        Expr::Lit(ExprLit {
            lit: Lit::Int(i), ..
        }) => i.base10_parse::<i128>().ok(),
        Expr::Unary(u) if matches!(u.op, UnOp::Neg(_)) => eval_int(&u.expr).map(|v| -v),
        Expr::Paren(p) => eval_int(&p.expr),
        _ => None,
    }
}

/// The C spelling of a Rust type, without a declarator name.
fn ctype(t: &Type, ctx: &str) -> Result<String, Error> {
    Ok(declare(t, "", ctx)?.trim_end().to_string())
}

/// A C declaration of `name` with Rust type `t`. Handles pointers and function pointers.
fn declare(t: &Type, name: &str, ctx: &str) -> Result<String, Error> {
    match t {
        Type::Ptr(p) => {
            let inner = declare(&p.elem, "", ctx)?;
            let qual = if p.mutability.is_some() { "" } else { "const " };
            Ok(format!("{qual}{inner} *{name}"))
        }
        Type::Reference(r) => {
            let inner = declare(&r.elem, "", ctx)?;
            let qual = if r.mutability.is_some() { "" } else { "const " };
            Ok(format!("{qual}{inner} *{name}"))
        }
        Type::BareFn(f) => {
            let ret = match &f.output {
                ReturnType::Default => "void".to_string(),
                ReturnType::Type(_, t) => ctype(t, ctx)?,
            };
            let mut params = Vec::new();
            for a in &f.inputs {
                params.push(ctype(&a.ty, ctx)?);
            }
            let plist = if params.is_empty() {
                "void".to_string()
            } else {
                params.join(", ")
            };
            Ok(format!("{ret} (*{name})({plist})"))
        }
        Type::Tuple(tt) if tt.elems.is_empty() => Ok(if name.is_empty() {
            "void".to_string()
        } else {
            format!("void {name}")
        }),
        Type::Path(tp) => {
            let seg = tp.path.segments.last().ok_or_else(|| Error {
                message: format!("`{ctx}`: empty type path"),
            })?;
            let c = match seg.ident.to_string().as_str() {
                "i8" => "int8_t".into(),
                "i16" => "int16_t".into(),
                "i32" => "int32_t".into(),
                "i64" => "int64_t".into(),
                "u8" => "uint8_t".into(),
                "u16" => "uint16_t".into(),
                "u32" => "uint32_t".into(),
                "u64" => "uint64_t".into(),
                "usize" => "size_t".into(),
                "isize" => "ptrdiff_t".into(),
                "bool" => "bool".into(),
                "f32" => "float".into(),
                "f64" => "double".into(),
                "c_void" => "void".into(),
                "c_char" => "char".into(),
                "c_int" => "int".into(),
                "c_uint" => "unsigned int".into(),
                "c_long" => "long".into(),
                "c_ulong" => "unsigned long".into(),
                "c_double" => "double".into(),
                "c_float" => "float".into(),
                other => other.to_string(),
            };
            Ok(if name.is_empty() {
                c
            } else {
                format!("{c} {name}")
            })
        }
        _ => fail(format!(
            "`{ctx}`: unsupported type; only primitives, pointers, named types and extern \"C\" fn pointers are supported"
        )),
    }
}
