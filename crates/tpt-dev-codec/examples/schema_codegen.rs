//! One schema, four artefacts.
//!
//! The schema below is the only place where the message layout is written.
//! From it, this example generates:
//!
//! 1. `examples/generated/sensor.rs`: the codec `Layout` (`tpt-dev-codec`), and
//!    a text parser: a `tpt-dev-dsl` grammar run through `PackratStream`, which
//!    is built on the `tpt-dev-ast` lexer, so input can arrive in chunks.
//! 2. `examples/generated/sensor.h`: a C header with the field positions and a
//!    struct of the field values.
//! 3. `tests/sensor_schema.rs`: round-trip, boundary, chunking and rejection
//!    tests, which load the generated module with `#[path]`.
//!
//! The generated files are committed. Rerun this example after changing the
//! schema, and the test file and module stay in step with it.
//!
//! Usage:
//!
//! ```text
//! cargo run -p tpt-dev-codec --example schema_codegen
//! ```

#![allow(clippy::print_stdout, clippy::print_stderr)]

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process;

use tpt_dev_codec::Endian;
use tpt_dev_codegen::Writer;

/// One field of the schema.
#[derive(Clone, Copy)]
struct Spec {
    name: &'static str,
    offset: u16,
    width: u8,
    endian: Endian,
}

/// The message: a sensor reading, 40 bits in five bytes.
const MESSAGE: &str = "sensor";
const SCHEMA: &[Spec] = &[
    Spec {
        name: "id",
        offset: 0,
        width: 8,
        endian: Endian::Little,
    },
    Spec {
        name: "temp",
        offset: 8,
        width: 12,
        endian: Endian::Little,
    },
    Spec {
        name: "flags",
        offset: 20,
        width: 4,
        endian: Endian::Little,
    },
    Spec {
        name: "seq",
        offset: 24,
        width: 16,
        endian: Endian::Big,
    },
];

/// Checks the schema, and returns the layout size in bytes. The codec checks
/// the layout again when the generated module is compiled, so a bad schema
/// that passes here still fails the build.
fn check_schema() -> Result<usize, String> {
    let mut end = 0usize;
    for (i, f) in SCHEMA.iter().enumerate() {
        if f.width == 0 || f.width > 64 {
            return Err(format!("{}: width {} is outside 1..=64", f.name, f.width));
        }
        if SCHEMA[..i].iter().any(|g| g.name == f.name) {
            return Err(format!("duplicate field {}", f.name));
        }
        if f.endian == Endian::Big && (f.offset % 8 != 0 || f.width % 8 != 0) {
            return Err(format!(
                "{}: big-endian fields must be byte-aligned",
                f.name
            ));
        }
        end = end.max(usize::from(f.offset) + usize::from(f.width));
    }
    Ok(end.div_ceil(8))
}

fn max_value(width: u8) -> u64 {
    if width >= 64 {
        u64::MAX
    } else {
        (1u64 << width) - 1
    }
}

fn endian_expr(e: Endian) -> &'static str {
    match e {
        Endian::Little => "bits",
        Endian::Big => "be",
    }
}

/// The codec field list and layout, and the grammar of the text form.
fn rust_module(bytes: usize) -> String {
    let n = SCHEMA.len();
    let mut w = Writer::new();
    w.line("//! Generated by tpt-dev-codec's examples/schema_codegen.rs from the sensor schema.");
    w.line("//! Do not edit by hand: rerun the example to regenerate.");
    w.blank();
    w.line("#![allow(dead_code)]");
    w.blank();
    w.line("use tpt_dev_codec::{CodecError, Field, Layout};");
    w.line("use tpt_dev_dsl::{Expr, Grammar, Rule};");
    w.line("use tpt_dev_dsl::PackratStream;");
    w.blank();
    let _ = w.constant("pub", "BYTES", "usize", &bytes.to_string());
    let _ = w.constant("pub", "FIELD_COUNT", "usize", &n.to_string());
    let names: Vec<String> = SCHEMA.iter().map(|f| format!("\"{}\"", f.name)).collect();
    let _ = w.constant(
        "pub",
        "FIELD_NAMES",
        &format!("[&str; {n}]"),
        &format!("[{}]", names.join(", ")),
    );
    let widths: Vec<String> = SCHEMA.iter().map(|f| f.width.to_string()).collect();
    let _ = w.constant(
        "pub",
        "FIELD_WIDTHS",
        &format!("[u8; {n}]"),
        &format!("[{}]", widths.join(", ")),
    );
    w.blank();
    w.line("/// The codec fields, in order.");
    let fields: Vec<String> = SCHEMA
        .iter()
        .map(|f| {
            format!(
                "Field::{}(\"{}\", {}, {})",
                endian_expr(f.endian),
                f.name,
                f.offset,
                f.width
            )
        })
        .collect();
    w.line(&format!(
        "pub const FIELDS: &[Field] = &[{}];",
        fields.join(", ")
    ));
    w.line("/// The layout, checked when it is built.");
    w.line(&format!(
        "pub const LAYOUT: Layout<{bytes}> = Layout::new(FIELDS);"
    ));
    w.blank();
    w.line("const DIGIT: Expr = Expr::Range(b'0', b'9');");
    w.line("const DIGITS: Expr = Expr::Seq(&[DIGIT, Expr::Repeat(&DIGIT)]);");
    w.blank();
    // Rule 0 is the whole record; rules 1..=n are the fields; rule n+1 is the digits.
    let digits_rule = n + 1;
    w.line("/// The text form: `id=7 temp=300 flags=3 seq=65535`, fields in schema order.");
    w.line("/// Rule 0 is the record, rules 1..=n the fields, rule n+1 the digits.");
    w.line("pub const GRAMMAR: Grammar = Grammar::new(&[");
    let mut record = Vec::new();
    for i in 0..n {
        if i > 0 {
            record.push("Expr::Lit(b\" \")".to_string());
        }
        record.push(format!("Expr::Call({})", i + 1));
    }
    w.line(&format!(
        "    Rule {{ name: \"record\", body: Expr::Seq(&[{}]) }},",
        record.join(", ")
    ));
    for f in SCHEMA {
        w.line(&format!(
            "    Rule {{ name: \"{0}\", body: Expr::Seq(&[Expr::Lit(b\"{0}=\"), Expr::Call({1})]) }},",
            f.name, digits_rule
        ));
    }
    w.line("    Rule { name: \"digits\", body: DIGITS },");
    w.line("]);");
    w.blank();
    w.line("/// Why a text record was refused.");
    w.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    w.line("pub enum ParseFail {");
    w.line("    /// The text does not match the grammar.");
    w.line("    Syntax,");
    w.line("    /// A value does not fit in its field's width.");
    w.line("    OutOfRange {");
    w.line("        /// The field that overflowed.");
    w.line("        field: &'static str,");
    w.line("    },");
    w.line("}");
    w.blank();
    w.line("/// Parses a text record given in chunks. The chunks may split the input anywhere.");
    w.line("pub fn parse_chunks(chunks: &[&[u8]]) -> Result<[u64; FIELD_COUNT], ParseFail> {");
    w.line("    let mut stream = PackratStream::<256, 512>::new(GRAMMAR, 0);");
    w.line("    for chunk in chunks {");
    w.line("        stream.feed(chunk).map_err(|_| ParseFail::Syntax)?;");
    w.line("    }");
    w.line("    if !stream.finish_recognise().map_err(|_| ParseFail::Syntax)? {");
    w.line("        return Err(ParseFail::Syntax);");
    w.line("    }");
    w.line("    // The grammar fixes the shape, so the values are the digits after each `name=`.");
    w.line("    let text: Vec<u8> = chunks.iter().flat_map(|c| c.iter().copied()).collect();");
    w.line("    let text = core::str::from_utf8(&text).map_err(|_| ParseFail::Syntax)?;");
    w.line("    let mut out = [0u64; FIELD_COUNT];");
    w.line("    for (i, pair) in text.split(' ').enumerate() {");
    w.line("        let value = pair.split_once('=').map(|(_, v)| v).ok_or(ParseFail::Syntax)?;");
    w.line("        let field = FIELD_NAMES[i];");
    w.line("        let v: u64 = value.parse().map_err(|_| ParseFail::OutOfRange { field })?;");
    w.line("        if v > (u64::MAX >> (64 - u32::from(FIELD_WIDTHS[i]))) {");
    w.line("            return Err(ParseFail::OutOfRange { field });");
    w.line("        }");
    w.line("        out[i] = v;");
    w.line("    }");
    w.line("    Ok(out)");
    w.line("}");
    w.blank();
    w.line("/// Parses a text record given in one piece.");
    w.line("pub fn parse(text: &[u8]) -> Result<[u64; FIELD_COUNT], ParseFail> {");
    w.line("    parse_chunks(&[text])");
    w.line("}");
    w.blank();
    w.line("/// Encodes the field values into the layout's bytes.");
    w.line("pub fn encode(values: &[u64; FIELD_COUNT]) -> Result<[u8; BYTES], CodecError> {");
    w.line("    let mut out = [0u8; BYTES];");
    w.line("    LAYOUT.encode(values, &mut out)?;");
    w.line("    Ok(out)");
    w.line("}");
    w.blank();
    w.line("/// Decodes the layout's bytes into field values.");
    w.line("pub fn decode(bytes: &[u8; BYTES]) -> Result<[u64; FIELD_COUNT], CodecError> {");
    w.line("    let mut out = [0u64; FIELD_COUNT];");
    w.line("    LAYOUT.decode(bytes, &mut out)?;");
    w.line("    Ok(out)");
    w.line("}");
    w.finish().unwrap_or_default()
}

fn c_header(bytes: usize) -> String {
    let upper = MESSAGE.to_uppercase();
    let mut out = String::new();
    let _ = writeln!(
        out,
        "/* Generated by tpt-dev-codec's examples/schema_codegen.rs from the {MESSAGE} schema.\n \
         * Do not edit by hand: rerun the example to regenerate.\n */"
    );
    let _ = writeln!(
        out,
        "#ifndef TPT_{upper}_H\n#define TPT_{upper}_H\n\n#include <stdint.h>\n"
    );
    let _ = writeln!(out, "#define TPT_{upper}_BYTES {bytes}");
    let _ = writeln!(out, "#define TPT_{upper}_FIELD_COUNT {}\n", SCHEMA.len());
    out.push_str("/* Bit position and width of each field in the layout. */\n");
    for f in SCHEMA {
        let n = f.name.to_uppercase();
        let _ = writeln!(out, "#define TPT_{upper}_{n}_OFFSET {}", f.offset);
        let _ = writeln!(out, "#define TPT_{upper}_{n}_WIDTH {}", f.width);
        if f.endian == Endian::Big {
            let _ = writeln!(out, "#define TPT_{upper}_{n}_BIG_ENDIAN 1");
        }
    }
    out.push_str("\n/* Field values, as the codec decodes them. */\n");
    let _ = writeln!(out, "typedef struct {{");
    for f in SCHEMA {
        let ty = match f.width {
            1..=8 => "uint8_t",
            9..=16 => "uint16_t",
            17..=32 => "uint32_t",
            _ => "uint64_t",
        };
        let _ = writeln!(out, "    {ty} {};", f.name);
    }
    let _ = writeln!(out, "}} tpt_{MESSAGE}_t;\n");
    let _ = writeln!(out, "#endif /* TPT_{upper}_H */");
    out
}

fn test_file(bytes: usize) -> String {
    let n = SCHEMA.len();
    let mut w = Writer::new();
    w.line("//! Generated by tpt-dev-codec's examples/schema_codegen.rs from the sensor schema.");
    w.line("//! Do not edit by hand: rerun the example to regenerate.");
    w.blank();
    w.line("#![allow(clippy::unwrap_used, clippy::panic, dead_code, unreachable_pub)]");
    w.blank();
    w.line("#[path = \"../examples/generated/sensor.rs\"]");
    w.line("mod sensor;");
    w.blank();
    let maxes: Vec<String> = SCHEMA
        .iter()
        .map(|f| max_value(f.width).to_string())
        .collect();
    w.line(&format!("const MAX: [u64; {n}] = [{}];", maxes.join(", ")));
    w.line("const EXAMPLE: &str = \"id=7 temp=300 flags=3 seq=65535\";");
    w.line(&format!("const BYTES: usize = {bytes};"));
    w.blank();
    w.line("#[test]");
    w.block("fn maximum_values_round_trip_through_the_layout()", |w| {
        w.line("let bytes = sensor::encode(&MAX).unwrap();");
        w.line("assert_eq!(sensor::decode(&bytes).unwrap(), MAX);");
    });
    w.blank();
    w.line("#[test]");
    w.block("fn each_field_at_its_maximum_round_trips_alone()", |w| {
        w.line("for i in 0..sensor::FIELD_COUNT {");
        w.line("    let mut values = [0u64; sensor::FIELD_COUNT];");
        w.line("    values[i] = MAX[i];");
        w.line("    let bytes = sensor::encode(&values).unwrap();");
        w.line("    assert_eq!(sensor::decode(&bytes).unwrap(), values, \"field {}\", sensor::FIELD_NAMES[i]);");
        w.line("}");
    });
    w.blank();
    w.line("#[test]");
    w.block("fn text_parses_to_the_values_the_codec_expects()", |w| {
        w.line("assert_eq!(sensor::parse(EXAMPLE.as_bytes()).unwrap(), [7, 300, 3, 65535]);");
    });
    w.blank();
    w.line("#[test]");
    w.block("fn chunked_text_parses_the_same_as_whole_text()", |w| {
        w.line("let bytes = EXAMPLE.as_bytes();");
        w.line("let whole = sensor::parse(bytes).unwrap();");
        w.line("let one_byte: Vec<&[u8]> = bytes.chunks(1).collect();");
        w.line("assert_eq!(sensor::parse_chunks(&one_byte).unwrap(), whole);");
        w.line("let uneven: Vec<&[u8]> = bytes.chunks(5).collect();");
        w.line("assert_eq!(sensor::parse_chunks(&uneven).unwrap(), whole);");
    });
    w.blank();
    w.line("#[test]");
    w.block("fn parsed_text_encodes_and_decodes_unchanged()", |w| {
        w.line("let values = sensor::parse(EXAMPLE.as_bytes()).unwrap();");
        w.line("let bytes = sensor::encode(&values).unwrap();");
        w.line("assert_eq!(sensor::decode(&bytes).unwrap(), values);");
    });
    w.blank();
    w.line("#[test]");
    w.block("fn values_wider_than_their_field_are_refused_by_both_paths()", |w| {
        w.line("for i in 0..sensor::FIELD_COUNT {");
        w.line("    let mut values = [0u64; sensor::FIELD_COUNT];");
        w.line("    values[i] = MAX[i] + 1;");
        w.line("    assert!(sensor::encode(&values).is_err(), \"encode accepted field {}\", sensor::FIELD_NAMES[i]);");
        w.line("}");
        w.line("let too_big = \"id=256 temp=300 flags=3 seq=65535\";");
        w.line("assert_eq!(sensor::parse(too_big.as_bytes()), Err(sensor::ParseFail::OutOfRange { field: \"id\" }));");
    });
    w.blank();
    w.line("#[test]");
    w.block("fn malformed_text_is_refused()", |w| {
        w.line("let cases = [");
        w.line("    \"\",");
        w.line("    \"id=7 temp=300 flags=3\",");
        w.line("    \"id=7 temp=300 seq=65535 flags=3\",");
        w.line("    \"id= temp=300 flags=3 seq=65535\",");
        w.line("    \"id=7 temp=300 flags=3 seq=65535 extra=1\",");
        w.line("    \"id=7 temp=300 flags=3 seq=6x\",");
        w.line("];");
        w.line("for case in cases {");
        w.line("    assert!(sensor::parse(case.as_bytes()).is_err(), \"accepted {case:?}\");");
        w.line("}");
    });
    w.finish().unwrap_or_default()
}

fn main() {
    let mut args = env::args().skip(1);
    let gen_dir = args
        .next()
        .unwrap_or_else(|| String::from("examples/generated"));
    let test_path = args
        .next()
        .unwrap_or_else(|| String::from("tests/sensor_schema.rs"));

    let bytes = match check_schema() {
        Ok(b) => b,
        Err(msg) => {
            eprintln!("schema_codegen: {msg}");
            process::exit(1);
        }
    };

    let gen_dir = Path::new(&gen_dir);
    if let Err(e) = fs::create_dir_all(gen_dir) {
        eprintln!("schema_codegen: cannot create {}: {e}", gen_dir.display());
        process::exit(2);
    }
    let outputs = [
        (gen_dir.join("sensor.rs"), rust_module(bytes)),
        (gen_dir.join("sensor.h"), c_header(bytes)),
        (Path::new(&test_path).to_path_buf(), test_file(bytes)),
    ];
    for (path, text) in outputs {
        if let Err(e) = fs::write(&path, text) {
            eprintln!("schema_codegen: cannot write {}: {e}", path.display());
            process::exit(2);
        }
        println!("wrote {}", path.display());
    }
}
