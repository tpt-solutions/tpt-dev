//! From a failed proof to a regression test.
//!
//! The contract under test is
//!
//! ```text
//! #[requires(x >= 0)]
//! #[ensures(result >= x)]
//! fn step_down(x: i64) -> i64 { x - 1 }
//! ```
//!
//! The solver tries to prove it. It asks whether `requires ∧ ¬ensures` is
//! satisfiable. It is, so the proof fails and the solver's models are
//! counterexamples. The example then:
//!
//! 1. collects counterexamples from the solver (`solver_seeds`),
//! 2. confirms each one by running the real function under the fuzzer,
//! 3. minimises each confirmed input, and
//! 4. writes one regression test per distinct minimal input to the file
//!    given on the command line.
//!
//! Usage:
//!
//! ```text
//! cargo run -p tpt-dev-contract --example counterexample_regression -- tests/regression_step_down.rs
//! ```

#![allow(clippy::print_stdout, clippy::print_stderr, clippy::panic)]

use std::env;
use std::fs;
use std::process;

use tpt_dev_fuzz::{Config, Coverage, Fuzzer, Outcome, minimise, solver_seeds};
use tpt_dev_solver::{Linear, Rational};

/// The function under test. Its contract is stated in the module docs.
fn step_down(x: i64) -> i64 {
    x - 1
}

/// The postcondition, checked by the fuzzer on each input.
fn target(v: &[i64], _cov: &mut Coverage) -> Outcome {
    let x = v[0];
    let result = step_down(x);
    if result >= x {
        Outcome::Pass
    } else {
        Outcome::Crash(format!(
            "ensures result >= x violated: x = {x}, result = {result}"
        ))
    }
}

/// Runs the proof. `Ok` holds the solver's counterexamples, and `Err` means the proof succeeded.
fn counterexamples() -> Result<Vec<Vec<i64>>, String> {
    solver_seeds(1, 16, |arena, v| {
        let x = Linear::var(v[0]);
        let zero = Linear::constant(Rational::from_int(0));
        let requires = arena.ge(&x, &zero)?;
        let result = x.checked_sub(&Linear::constant(Rational::from_int(1)))?;
        let ensures = arena.ge(&result, &x)?;
        let not_ensures = arena.not(ensures);
        Some(arena.and(vec![requires, not_ensures]))
    })
    .map_err(|e| format!("the solver did not produce counterexamples: {e:?}"))
}

fn regression_file(inputs: &[i64]) -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by tpt-dev-contract's examples/counterexample_regression.rs.\n\
         // Contract: requires x >= 0; ensures result >= x.\n\
         // Do not edit by hand: rerun the example to regenerate.\n\n",
    );
    out.push_str("fn step_down(x: i64) -> i64 {\n    x - 1\n}\n\n");
    out.push_str(
        "fn check(x: i64) {\n    let result = step_down(x);\n    \
         assert!(result >= x, \"ensures result >= x violated: x = {x}, result = {result}\");\n}\n",
    );
    for x in inputs {
        let name = if *x < 0 {
            format!("neg_{}", x.unsigned_abs())
        } else {
            format!("{x}")
        };
        out.push_str(&format!(
            "\n/// Counterexample from the failed proof. This is a known bug, so the test\n\
             /// expects the panic. Remove `#[should_panic]` once `step_down` satisfies its contract.\n\
             #[test]\n\
             #[should_panic(expected = \"ensures result >= x violated\")]\n\
             fn counterexample_{name}() {{\n    check({x});\n}}\n"
        ));
    }
    out
}

fn main() {
    let Some(out_path) = env::args().nth(1) else {
        eprintln!("usage: counterexample_regression <output.rs>");
        process::exit(2);
    };

    let seeds = match counterexamples() {
        Ok(seeds) => seeds,
        Err(msg) => {
            eprintln!("{msg}");
            process::exit(1);
        }
    };
    println!("proof failed: {} solver counterexamples", seeds.len());

    let mut fuzzer = Fuzzer::new(
        target,
        1,
        Config {
            iterations: 1_000,
            ..Config::default()
        },
    );
    let Some(found) = fuzzer.run(&seeds) else {
        eprintln!("no counterexample confirmed at run time: the proof and the code disagree");
        process::exit(1);
    };
    println!("confirmed by fuzzer: {}", found.message);

    let mut inputs = Vec::new();
    for seed in &seeds {
        let mut t = target;
        if let Some((min, message)) = minimise(&mut t, seed)
            && !inputs.contains(&min[0])
        {
            println!("minimal counterexample x = {}: {message}", min[0]);
            inputs.push(min[0]);
        }
    }
    inputs.sort_unstable();

    if let Err(e) = fs::write(&out_path, regression_file(&inputs)) {
        eprintln!("cannot write {out_path}: {e}");
        process::exit(1);
    }
    println!("wrote {} regression tests to {out_path}", inputs.len());
}
